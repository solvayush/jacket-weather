#!/usr/bin/env node
// Bundles chapters/chN/chapter.js (CommonJS factories) into chapters.bundle.js for file:// use (classic script, no modules).
// Only chapters that have a chapters/chN.done marker are included. Run: node build.js   (options: --only ch4,ch7  --out file)
const fs = require('fs'), path = require('path');
const root = __dirname, dir = path.join(root, 'chapters');
const args = process.argv.slice(2), opt = n => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const only = opt('--only') ? opt('--only').split(',') : null, outFile = opt('--out') || path.join(root, 'chapters.bundle.js');
const parts = [], included = [];
for (let n = 1; n <= 8; n++) {
  if (only && only.indexOf('ch' + n) < 0) continue;
  const src = path.join(dir, 'ch' + n, 'chapter.js'), done = path.join(dir, 'ch' + n + '.done');
  if (!fs.existsSync(src) || !fs.existsSync(done)) continue;
  const code = fs.readFileSync(src, 'utf8');
  try { new Function('module', 'exports', code); } catch (e) { console.error('ch' + n + ' has a syntax error, skipped: ' + e.message); continue; }
  parts.push("  { id: 'ch" + n + "', factory: (function () { var module = { exports: {} }; var exports = module.exports;\n" + code + "\n    return module.exports; })() }");
  included.push('ch' + n);
}
const out = '/* generated by build.js - do not edit */\nwindow.CHAPTER_FACTORIES = [\n' + parts.join(',\n') + '\n];\n';
fs.writeFileSync(outFile, out);
console.log(path.basename(outFile) + ' written: ' + (included.join(', ') || '(no chapters)') + ' (' + out.length + ' bytes)');
